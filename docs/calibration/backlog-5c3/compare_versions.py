#!/usr/bin/env python3
"""Slice 5C.3: every committed development strategy under v0.2-eval-3 (set
p5-eval3, unchanged) beside v0.2-eval-4 (set p6-eval4), and the D2 / E3
comparison. Reads the reports; decides nothing.

    python3 docs/calibration/backlog-5c3/compare_versions.py > docs/calibration/backlog-5c3/reevaluation.md
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DEV = os.path.join(HERE, "..", "strategy-development")
K = 100000.0


def find(sid, name):
    for base in ("results", "detail"):
        p = os.path.join(DEV, base, sid, name)
        if os.path.exists(p):
            return p
    raise SystemExit("missing %s/%s" % (sid, name))


def iv(x):
    if not x or not x.get("defined"):
        return "—"
    return "%.1f [%.1f, %.1f]" % (x["mean"] / K, x["lo"] / K, x["hi"] / K)


def summary(rep):
    plans = {p["plan"]: p for p in rep["plans"]}
    comps = {c["candidate"]: c for c in rep["comparisons"] if c["against"] == rep["baseline"]}
    out = {}
    for n, p in plans.items():
        c = comps.get(n, {})
        j = p["serviceJoint"]
        out[n] = {"plan": p, "comp": c, "joint": len(j["failingSeeds"]) + len(j["insufficientSeeds"]), "service": p["serviceStatus"],
                  "backlog": p["backlogStableSeeds"], "backlogStatus": p["backlogStatus"], "funding": p["fundingStatus"],
                  "solvent": p["solvencyStatus"], "verdict": c.get("verdict", "(baseline)"), "class": c.get("classification", "—")}
    return out


def main():
    v3 = summary(json.load(open(find("p5-eval3", "report.json"))))
    rep4 = json.load(open(find("p6-eval4", "report.json")))
    v4 = summary(rep4)
    print("# Re-evaluation: v0.2-eval-3 against v0.2-eval-4 (development seeds 901–910)")
    print()
    print("Generated by `compare_versions.py`. v0.2-eval-3: set `p5-eval3` (`../strategy-development/results/p5-eval3`), unchanged. "
          "v0.2-eval-4: set `p6-eval4`, the same strategy files, records and horizon. Only the backlog rule changed, so every "
          "other column must agree. Development evidence: 10 seeds, exploratory.")
    print()
    print("| Plan | Seeds failing service v3 → v4 | Funding v3 → v4 | Solvency v3 → v4 | Backlog-stable seeds v3 → v4 | Backlog gate v4 | Verdict v3 → v4 | Classification v4 |")
    print("|---|---|---|---|---|---|---|---|")
    for n in v4:
        a, b = v3[n], v4[n]
        print("| %s | %d → %d | %s → %s | %s → %s | %d → %d | %s | %s → %s | %s |" % (n, a["joint"], b["joint"], a["funding"], b["funding"],
                                                                              a["solvent"], b["solvent"], a["backlog"], b["backlog"],
                                                                              b["backlogStatus"], a["verdict"], b["verdict"], b["class"]))
    print()
    print("## Finance, v0.2-eval-4 ($k, mean [95% t], against A-no-action)")
    print()
    print("| Plan | T90 profit (absolute) | T90 Δ (incremental) | D31–90 Δ | T180 Δ |")
    print("|---|---|---|---|---|")
    for n, b in v4.items():
        f = b["comp"].get("financial")
        if not f:
            continue
        print("| %s | %s | %s | %s | %s |" % (n, iv(f["t90AbsoluteCents"]), iv(f["t90IncrementCents"]), iv(f["operatingWindowIncrementCents"]),
                                          iv(f["t180IncrementCents"])))
    print()
    print("## D2 against E3 (v0.2-eval-4)")
    print()
    print("Pooled breach rates over the gated period (urgent) and T90 / tail (soon, routine), %; the worst seed's urgent rate; seeds failing the joint rule.")
    print()
    print("| Plan | Urgent, gated | Worst seed urgent | Soon T90 / tail | Routine T90 / tail | Joint failing seeds | Backlog stable | T90 Δ | Classification |")
    print("|---|---|---|---|---|---|---|---|---|")
    for n in ("D2-full-reading-alloc65", "E3-urgent-weeknights-alloc65", "E2-urgent-tele-alloc65"):
        p, c = v4[n]["plan"], v4[n]["comp"]

        def g(w, q):
            for x in p["serviceGates"]:
                if x["window"] == w and x["stratum"] == q:
                    return x
            return None
        u = g("gated", "urgent")
        def r(x):
            return "%.1f" % (100 * x["pooled"]["value"]) if x and x["pooled"].get("defined") else "—"
        ws = max(x["value"] for sr in p["perSeed"] for x in sr["gates"] if x["window"] == "gated" and x["stratum"] == "urgent")
        print("| %s | %s | %.1f | %s / %s | %s / %s | %d | %d / 10 | %s | %s |" % (
            n, r(u), 100 * ws, r(g("T90", "soon")), r(g("tail", "soon")), r(g("T90", "routine")), r(g("tail", "routine")),
            v4[n]["joint"], v4[n]["backlog"], iv(c["financial"]["t90IncrementCents"]), c["classification"]))


if __name__ == "__main__":
    main()
