#!/usr/bin/env python3
"""Slice 5C.2: every committed development strategy under v0.2-eval-2 (the
Slice 5C.1 reports, unchanged) beside v0.2-eval-3 (set p5-eval3). Reads
the reports; decides nothing.

    python3 docs/calibration/policy-5c2/compare_versions.py > docs/calibration/policy-5c2/reevaluation.md
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DEV = os.path.join(HERE, "..", "strategy-development")


def load(path):
    return json.load(open(path))


def find(sid, name):
    for base in ("results", "detail"):
        p = os.path.join(DEV, base, sid, name)
        if os.path.exists(p):
            return p
    raise SystemExit("missing %s/%s" % (sid, name))


def summary(rep):
    plans = {p["plan"]: p for p in rep["plans"]}
    comps = {c["candidate"]: c for c in rep["comparisons"] if c["against"] == rep["baseline"]}
    out = {}
    for n, p in plans.items():
        c = comps.get(n, {})
        j = p["serviceJoint"]
        out[n] = {
            "joint": len(j["failingSeeds"]) + len(j["insufficientSeeds"]), "service": p["serviceStatus"],
            "funding": len(p["fundingGapSeeds"]), "backlog": p["backlogStableSeeds"], "solvent": p["solvencyStatus"],
            "verdict": c.get("verdict", "(baseline)"), "class": c.get("classification", "—"),
        }
    return out


def main():
    v2 = {}
    for sid in ("p1-historical", "p2-family", "p3-refine", "p4-refine"):
        for n, s in summary(load(find(sid, "report.json"))).items():
            v2.setdefault(n, s)
    v3 = summary(load(find("p5-eval3", "report.json")))
    print("# Re-evaluation: v0.2-eval-2 against v0.2-eval-3 (development seeds 901–910)")
    print()
    print("Generated by `compare_versions.py`. v0.2-eval-2: the Slice 5C.1 reports (`../strategy-development/results/p1–p4`), unchanged. "
          "v0.2-eval-3: set `p5-eval3`, the same strategy files in one evaluation (H = day 150 in both). "
          "Service (joint seed rule, thresholds) is unchanged between the versions, so its columns must agree.")
    print()
    print("| Plan | Seeds failing service v2 → v3 | Funding-gap seeds v2 → v3 | Backlog-stable seeds v2 → v3 | Solvency v2 → v3 | Verdict v2 → v3 | Classification v3 |")
    print("|---|---|---|---|---|---|---|")
    for n in v3:
        a, b = v2.get(n), v3[n]
        if a is None:
            continue
        print("| %s | %d → %d | %d → %d | %d → %d | %s → %s | %s → %s | %s |" % (n, a["joint"], b["joint"], a["funding"], b["funding"],
                                                                         a["backlog"], b["backlog"], a["solvent"], b["solvent"],
                                                                         a["verdict"], b["verdict"], b["class"]))


if __name__ == "__main__":
    main()
