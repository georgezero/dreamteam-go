#!/usr/bin/env python3
"""Tabulates the V0.2 Step 0 feasibility sweep from
docs/calibration/feasibility/results/*.json into results/feasibility.md.
Run from the repository root after the sweep:

    python3 docs/calibration/feasibility/report.py

Means across seeds with the range in parentheses. Deltas are paired by
seed against the base manifest (D100: the established practice, no
overlay) run with the same seeds; money is per 30 days unless noted."""
import glob, json, os, statistics

ROOT = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(ROOT, "results")

def load():
    out = {}
    for p in sorted(glob.glob(os.path.join(RES, "*.json"))):
        r = json.load(open(p))
        out[r["experiment"]["name"]] = r
    return out

def per_seed(r, win, f):
    return {s["seed"]: f(s["windows"][win]) for s in r["perSeed"]}

def k30(w, cents):  # $k per 30 days
    return cents / 100_000 * 30 / w["days"]

METRICS = {
    "exams30": lambda w: sum(w["exams"]) * 30 / w["days"],
    "reports30": lambda w: w["reports"] * 30 / w["days"],
    "rev30": lambda w: k30(w, w["netRevenueCents"]),
    "labor30": lambda w: k30(w, w["laborCents"]),
    "other30": lambda w: k30(w, w["fixedCents"] + w["variableCents"]),
    "profit30": lambda w: k30(w, w["profitCents"]),
    "profit": lambda w: w["profitCents"] / 100_000,
    "margin": lambda w: w["marginBP"] / 100,
    "lost": lambda w: sum(w["lostDeclined"]) + sum(w["lostNoSlot"]),
    "orders": lambda w: sum(w["orders"]),
    "left": lambda w: w["walkInsLeft"],
    "cash": lambda w: w["cashEndCents"] / 100_000,
    "ot": lambda w: w["overtimeMin"] / 60,
    "techUtil": lambda w: w["techUtilBP"] / 100,
    "readUtil": lambda w: w["readUtilBP"] / 100,
}
for i, md in enumerate(["XR", "US", "CT", "MR"]):
    METRICS["util" + md] = (lambda i: lambda w: w["utilStaffedBP"][i] / 100)(i)
    METRICS["leadP50" + md] = (lambda i: lambda w: w["leadP50Days"][i])(i)
    METRICS["leadP90" + md] = (lambda i: lambda w: w["leadP90Days"][i])(i)
    METRICS["lost" + md] = (lambda i: lambda w: w["lostDeclined"][i] + w["lostNoSlot"][i])(i)
    METRICS["exams30" + md] = (lambda i: lambda w: w["exams"][i] * 30 / w["days"])(i)
for pri in ("urgent", "soon", "routine"):
    for f, key in (("P50", "p50Min"), ("P90", "p90Min"), ("Max", "maxMin"), ("Breaches", "breaches"), ("Unfinished", "unfinished")):
        METRICS[pri + f] = (lambda pri, key: lambda w: w["tatByPriority"].get(pri, {}).get(key, 0))(pri, key)

def agg(xs):
    xs = list(xs)
    return statistics.mean(xs), min(xs), max(xs), (statistics.stdev(xs) if len(xs) > 1 else 0.0)

def cell(xs, fmt="%.1f"):
    m, lo, hi, _ = agg(xs)
    return (fmt + " (" + fmt + "–" + fmt + ")") % (m, lo, hi)

def main():
    rs = load()
    base = rs.get("D100")
    names = sorted(rs, key=lambda n: (n.split("-")[0], len(n), n))
    L = []
    w = L.append
    w("# V0.2 Step 0 feasibility sweep — results\n")
    w("Generated by `docs/calibration/feasibility/report.py` from `results/*.json` (the calibration\n"
      "harness, manifests in `experiments/`, generated by `generate.py`); do not edit by hand. Static\n"
      "overlays on the established practice; no actions; default policies. Means across seeds with\n"
      "the range in parentheses; money in $k per 30 days unless noted. Δ columns are paired by seed\n"
      "against `D100` (the established practice without an overlay); the 20-seed `-s20` manifests\n"
      "against `D100-s20`.\n")
    if base:
        r0 = base
        w("Engine `%s`; base scenario fingerprint `%s`.\n" % (r0["engine"], r0["baseScenarioFingerprint"]))
    for win in ("90d", "30d"):
        w("\n## Economics, %s window\n" % win)
        w("| manifest | seeds | fingerprint | exams / 30 d | reports / 30 d | net revenue | labor | other opex | operating profit | Δ profit vs D100 | margin % | margin sd | cash at end $k |")
        w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for n in names:
            r = rs[n]
            v = {m: per_seed(r, win, f) for m, f in METRICS.items() if m in ("exams30", "reports30", "rev30", "labor30", "other30", "profit30", "margin", "cash")}
            d = ""
            ref = rs.get("D100-s20") if n.endswith("-s20") else base
            if ref and n not in ("D100", "D100-s20"):
                b = per_seed(ref, win, METRICS["profit30"])
                common = [s for s in v["profit30"] if s in b]
                if common:
                    d = cell([v["profit30"][s] - b[s] for s in common])
            sd = agg(v["margin"].values())[3]
            w("| %s | %s | `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %.1f | %s |" % (
                n, r["experiment"]["seeds"], r["scenarioFingerprint"][:12], cell(v["exams30"].values(), "%.0f"), cell(v["reports30"].values(), "%.0f"),
                cell(v["rev30"].values()), cell(v["labor30"].values()), cell(v["other30"].values()), cell(v["profit30"].values()), d,
                cell(v["margin"].values()), sd, cell(v["cash"].values(), "%.0f")))
    win = "90d"
    w("\n## Access and utilization, 90-day window\n")
    w("Staffed utilization is time-weighted room use over staffed time; lead is received → appointment day\n"
      "(booked referral orders), p50 / p90; lost counts referral orders that could not be booked within\n"
      "the patient's tolerance or the horizon.\n")
    w("| manifest | referral orders | lost (all) | walk-ins left | XR util / lead / lost | US util / lead / lost | CT util / lead / lost | MR util / lead / lost | tech busy % | reading used % | overtime h |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for n in names:
        r = rs[n]
        g = lambda m: [v for v in per_seed(r, win, METRICS[m]).values()]
        mod = lambda md: "%.0f%% / %.0f·%.0f d / %.0f" % (statistics.mean(g("util" + md)), statistics.mean(g("leadP50" + md)), statistics.mean(g("leadP90" + md)), statistics.mean(g("lost" + md)))
        w("| %s | %.0f | %s | %s | %s | %s | %s | %s | %.0f | %.0f | %.0f |" % (n, statistics.mean(g("orders")), cell(g("lost"), "%.0f"), cell(g("left"), "%.0f"),
            mod("XR"), mod("US"), mod("CT"), mod("MR"), statistics.mean(g("techUtil")), statistics.mean(g("readUtil")), statistics.mean(g("ot"))))
    w("\n## Report turnaround, 90-day window\n")
    w("Studies acquired in the window, as of its end; minutes. Breaches: completed over target plus\n"
      "unfinished past it (targets: urgent 60, soon 240, routine 1,440 min).\n")
    w("| manifest | urgent p50 / p90 | urgent max | urgent breaches | soon p90 | soon breaches | routine p50 / p90 | routine max | routine breaches |")
    w("|---|---|---|---|---|---|---|---|---|")
    for n in names:
        r = rs[n]
        g = lambda m: [v for v in per_seed(r, win, METRICS[m]).values()]
        mn = lambda m: statistics.mean(g(m))
        w("| %s | %.0f / %.0f | %s | %s | %.0f | %s | %.0f / %.0f | %s | %s |" % (n, mn("urgentP50"), mn("urgentP90"), cell(g("urgentMax"), "%.0f"), cell(g("urgentBreaches"), "%.0f"),
            mn("soonP90"), cell(g("soonBreaches"), "%.0f"), mn("routineP50"), mn("routineP90"), cell(g("routineMax"), "%.0f"), cell(g("routineBreaches"), "%.0f")))
    w("\n## Per-seed operating profit, 90-day window ($k over the window)\n")
    seeds = sorted({s["seed"] for r in rs.values() for s in r["perSeed"]})
    w("| manifest | " + " | ".join(str(s) for s in seeds) + " |")
    w("|---|" + "---|" * len(seeds))
    for n in names:
        p = per_seed(rs[n], win, METRICS["profit"])
        w("| %s | " % n + " | ".join(("%.1f" % p[s]) if s in p else "" for s in seeds) + " |")
    open(os.path.join(RES, "feasibility.md"), "w").write("\n".join(L) + "\n")
    print("wrote", os.path.join(RES, "feasibility.md"))

if __name__ == "__main__":
    main()
