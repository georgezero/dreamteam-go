#!/usr/bin/env python3
"""Tabulates V0.2 Step 0C (staffing architectures) from step0c/results/*.json
into step0c/results/step0c.md. Run from the repository root after the runs:

    python3 docs/calibration/feasibility/step0c/report.py

Names are <demand>-<architecture>-<MR coverage>[-<allocation>][-s20]. Every
delta is paired by seed against the control at the same demand and seeds
(<demand>-SHR-MRft, the Step 0B best configuration at that demand); the 95%
interval is the paired t interval of the mean delta. Money in $k per 30 days
unless noted; means across seeds with the range in parentheses."""
import glob, json, os, statistics

ROOT = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(ROOT, "results")
T95 = {8: 2.306, 19: 2.093}
MODS = ["XR", "US", "CT", "MR"]


def load():
    out = {}
    for p in sorted(glob.glob(os.path.join(RES, "*.json"))):
        r = json.load(open(p))
        out[r["experiment"]["name"]] = r
    return out


def k30(w, c):
    return c / 100_000 * 30 / w["days"]


def lost(w, md):
    i = w["mods"].index(md)
    return w["lostDeclined"][i] + w["lostNoSlot"][i]


def tat(w, pri, key):
    return w["tatByPriority"].get(pri, {}).get(key, 0)


M = {
    "margin": lambda w: w["marginBP"] / 100,
    "profit30": lambda w: k30(w, w["profitCents"]),
    "rev30": lambda w: k30(w, w["netRevenueCents"]),
    "labor30": lambda w: k30(w, w["laborCents"]),
    "read30": lambda w: k30(w, w["readingCostEstCents"]),
    "tech30": lambda w: k30(w, w["laborCents"] - w["readingCostEstCents"]),
    "minCash": lambda w: w["minCashCents"] / 100_000,
    "exams30": lambda w: sum(w["exams"]) * 30 / w["days"],
    "reports30": lambda w: w["reports"] * 30 / w["days"],
    "lostRef": lambda w: sum(w["lostDeclined"]) + sum(w["lostNoSlot"]),
    "left": lambda w: w["walkInsLeft"],
    "cash": lambda w: w["cashEndCents"] / 100_000,
    "liab": lambda w: (w["payablesEndCents"] + w["accruedPayrollEndCents"]) / 100_000,
    "ar": lambda w: w["receivablesEndCents"] / 100_000,
    "techH": lambda w: w["techDutyHours"] * 7 / w["days"],
    "techUtil": lambda w: w["techUtilBP"] / 100,
    "readUtil": lambda w: w["readUtilBP"] / 100,
    "ot": lambda w: w["overtimeMin"] / 60,
    "uP90": lambda w: tat(w, "urgent", "p90Min"),
    "uBr": lambda w: tat(w, "urgent", "breaches"),
    "uMax": lambda w: tat(w, "urgent", "maxMin"),
    "rP90": lambda w: tat(w, "routine", "p90Min"),
    "rMax": lambda w: tat(w, "routine", "maxMin"),
    "rUnf": lambda w: tat(w, "routine", "unfinished"),
}
for md in MODS:
    M["ex" + md] = (lambda md: lambda w: w["exams"][w["mods"].index(md)] * 30 / w["days"])(md)
    M["rp" + md] = (lambda md: lambda w: w["reportsByModality"][w["mods"].index(md)] * 30 / w["days"])(md)
    M["lost" + md] = (lambda md: lambda w: lost(w, md))(md)
    M["stH" + md] = (lambda md: lambda w: w["staffedHours"][w["mods"].index(md)] * 7 / w["days"])(md)
    M["util" + md] = (lambda md: lambda w: w["utilStaffedBP"][w["mods"].index(md)] / 100)(md)
for md in ("CT", "XR"):
    for c in ("shared_tech", "not_rostered", "no_supervision", "notice", "template_category", "category_full", "no_template_slot"):
        M[md + ":" + c] = (lambda md, c: lambda w: w["lossPrimary"].get(md, {}).get(c, 0))(md, c)


def series(r, win, f):
    return {s["seed"]: f(s["windows"][win]) for s in r["perSeed"]}


def mean(xs):
    return statistics.mean(list(xs))


def cell(d, fmt="%.1f"):
    xs = list(d.values())
    return (fmt + " (" + fmt + "–" + fmt + ")") % (mean(xs), min(xs), max(xs))


def delta(r, ref, win, f):
    a, b = series(r, win, f), series(ref, win, f)
    ds = [a[s] - b[s] for s in a if s in b]
    m = mean(ds)
    if len(ds) < 2:
        return m, m, m
    h = T95.get(len(ds) - 1, 2.0) * statistics.stdev(ds) / len(ds) ** 0.5
    return m, m - h, m + h


def dcell(r, ref, win, f, fmt="%+.1f"):
    if ref is None or r is ref:
        return "—"
    m, lo, hi = delta(r, ref, win, f)
    return (fmt + " (" + fmt + " to " + fmt + ")") % (m, lo, hi)


def parts(n):
    p = n.split("-")
    s20 = p[-1] == "s20"
    if s20:
        p = p[:-1]
    alloc = p[3] if len(p) > 3 else "A60"
    return p[0], p[1], p[2], alloc, s20


ARCH_ORDER = ["SHR", "DED", "DEDft", "DPT", "DPTft", "FLT", "FLTft"]


def key(n):
    d, a, mr, al, s20 = parts(n)
    return (s20, ["W130", "W115", "W150"].index(d), ARCH_ORDER.index(a), mr, al)


def main():
    rs = load()
    names = sorted(rs, key=key)

    def ref_of(n):
        d, _, _, _, s20 = parts(n)
        return rs.get("%s-SHR-MRft%s" % (d, "-s20" if s20 else ""))

    L = []
    w = L.append
    w("# V0.2 Step 0C — staffing architectures, results\n")
    w("Generated by `docs/calibration/feasibility/step0c/report.py` from `results/*.json`; do not\n"
      "edit by hand. Static overlays on the established practice (12-minute XR slots and\n"
      "imaging-weighted demand on every row); no actions; default policies. Δ columns are paired by\n"
      "seed against `<demand>-SHR-MRft` (shared XR/CT coverage, full-time MR evening: the Step 0B\n"
      "best configuration) with the 95% paired t interval. Money in $k per 30 days; T30 and T90\n"
      "are the 30- and 90-day windows from the takeover. Reading (est.) is the radiologists' salaries\n"
      "and benefits at their site allocation; Other labor is all other labor (technologists, front\n"
      "desk, operations manager).\n")
    w("Architectures: SHR shared (control) · DED dedicated day core, shared part-time evening ·\n"
      "DEDft dedicated core, shared full-time evening · DPT dedicated core and part-time dedicated\n"
      "evenings · DPTft the same with full-time evening shifts · FLT part-time float in the measured\n"
      "conflict periods · FLTft the float full-time. MR evening: MRft 11:30–20:00, MRpt 16:00–20:00.\n"
      "A62/A65/A70: radiologist site allocation 62.5/52.5%, 65/55% and 70/60% (base 60/50%).\n")
    for win in ("90d", "30d"):
        w("\n## Economics, T%s\n" % win[:-1])
        w("| Run | Seeds | Margin % | Profit | Median | Δ profit (95% CI) | Profitable | Revenue | Other labor | Reading (est.) |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        for n in names:
            r = rs[n]
            pr = series(r, win, M["profit30"])
            w("| %s | %d | %s | %s | %.1f | %s | %d/%d | %.1f | %.1f | %.1f |" % (
                n, len(pr), cell(series(r, win, M["margin"])), cell(pr), statistics.median(pr.values()),
                dcell(r, ref_of(n), win, M["profit30"]),
                sum(1 for v in pr.values() if v > 0), len(pr), mean(series(r, win, M["rev30"]).values()),
                mean(series(r, win, M["tech30"]).values()), mean(series(r, win, M["read30"]).values())))
    w("\n## Days 31–90 and cash\n")
    w("Operating profit of days 31–90 (T90 − T30, $k per 30 days); lowest cash in the 90 days ($k,\n"
      "sampled daily at 06:00) and the day of the lowest seed.\n")
    w("| Run | Days 31–90 profit | Profitable | Lowest cash | Day (lowest seed) |")
    w("|---|---|---|---|---|")
    for n in names:
        r = rs[n]
        late = {s["seed"]: (s["windows"]["90d"]["profitCents"] - s["windows"]["30d"]["profitCents"]) / 100_000 / 2
                for s in r["perSeed"]}
        mc = series(r, "90d", M["minCash"])
        low = min(r["perSeed"], key=lambda s: s["windows"]["90d"]["minCashCents"])
        w("| %s | %s | %d/%d | %s | %d |" % (n, cell(late), sum(1 for v in late.values() if v > 0), len(late), cell(mc),
                                           low["windows"]["90d"]["minCashDay"]))
    win = "90d"
    w("\n## Volume and access, T90\n")
    w("Exams and final reports per 30 days by modality; referral losses over 90 days.\n")
    w("| Run | Exams XR/US/CT/MR | Reports XR/US/CT/MR | Δ exams | Lost XR/US/CT/MR | Δ lost | Walk-ins left |")
    w("|---|---|---|---|---|---|---|")
    for n in names:
        r = rs[n]
        ex = "/".join("%.0f" % mean(series(r, win, M["ex" + m]).values()) for m in MODS)
        rp = "/".join("%.0f" % mean(series(r, win, M["rp" + m]).values()) for m in MODS)
        lo = "/".join("%.0f" % mean(series(r, win, M["lost" + m]).values()) for m in MODS)
        w("| %s | %s | %s | %s | %s | %s | %.0f |" % (n, ex, rp, dcell(r, ref_of(n), win, M["exams30"], "%+.0f"), lo,
                                                     dcell(r, ref_of(n), win, M["lostRef"], "%+.0f"),
                                                     mean(series(r, win, M["left"]).values())))
    w("\n## Booking-loss causes, T90 (primary cause, CT and XR, per 90 days)\n")
    w("| Run | CT shared / not rostered / supervision / notice / full | XR shared / not rostered / notice / full |")
    w("|---|---|---|")
    for n in names:
        r = rs[n]
        f = lambda k: "%.0f" % mean(series(r, win, M[k]).values())
        ct = " / ".join(f("CT:" + c) for c in ("shared_tech", "not_rostered", "no_supervision", "notice", "category_full"))
        xr = " / ".join(f("XR:" + c) for c in ("shared_tech", "not_rostered", "notice", "category_full"))
        w("| %s | %s | %s |" % (n, ct, xr))
    w("\n## Coverage and utilization, T90\n")
    w("Qualified staffed hours a week per room during open hours (a technologist shared between two\n"
      "rooms staffs both); technologist on-duty hours a week (paid, incl. run-over); utilization is\n"
      "busy / staffed.\n")
    w("| Run | Staffed h/wk XR/US/CT/MR | Tech duty h/wk | Tech util % | Room util XR/US/CT/MR % | Overtime h |")
    w("|---|---|---|---|---|---|")
    for n in names:
        r = rs[n]
        st = "/".join("%.0f" % mean(series(r, win, M["stH" + m]).values()) for m in MODS)
        ut = "/".join("%.0f" % mean(series(r, win, M["util" + m]).values()) for m in MODS)
        w("| %s | %s | %.0f | %.0f | %s | %.0f |" % (n, st, mean(series(r, win, M["techH"]).values()),
                                                   mean(series(r, win, M["techUtil"]).values()), ut,
                                                   mean(series(r, win, M["ot"]).values())))
    w("\n## Reporting, T90\n")
    w("Report turnaround (acquisition to final), minutes; breaches over 90 days.\n")
    w("| Run | Read util % | Urgent p90 | Urgent max | Urgent breaches | Routine p90 | Routine max | Routine unfinished |")
    w("|---|---|---|---|---|---|---|---|")
    for n in names:
        r = rs[n]
        g = lambda k: mean(series(r, win, M[k]).values())
        w("| %s | %.0f | %.0f | %.0f | %.1f | %.0f | %.0f | %.1f |" % (n, g("readUtil"), g("uP90"), g("uMax"), g("uBr"),
                                                                     g("rP90"), g("rMax"), g("rUnf")))
    w("\n## Cash and obligations at T90 ($k)\n")
    w("| Run | Cash | Payables + accrued payroll | Receivables |")
    w("|---|---|---|---|")
    for n in names:
        r = rs[n]
        w("| %s | %s | %.1f | %.1f |" % (n, cell(series(r, win, M["cash"])), mean(series(r, win, M["liab"]).values()),
                                         mean(series(r, win, M["ar"]).values())))
    w("\n## Per-seed operating profit, T90 ($k per 30 days)\n")
    seeds = sorted({s["seed"] for r in rs.values() for s in r["perSeed"]})
    w("| Run | " + " | ".join(str(s) for s in seeds) + " |")
    w("|---|" + "---|" * len(seeds))
    for n in names:
        pr = series(rs[n], win, M["profit30"])
        w("| %s | " % n + " | ".join(("%.1f" % pr[s]) if s in pr else "" for s in seeds) + " |")
    w("\n## Fingerprints\n")
    w("| Run | Scenario fingerprint | Overlay SHA-256 |")
    w("|---|---|---|")
    for n in names:
        r = rs[n]
        w("| %s | `%s` | `%s` |" % (n, r["scenarioFingerprint"][:16], (r.get("overlaySHA256") or "")[:16]))
    open(os.path.join(RES, "step0c.md"), "w").write("\n".join(L) + "\n")
    print(len(names), "runs")


if __name__ == "__main__":
    main()
