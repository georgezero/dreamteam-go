#!/usr/bin/env python3
"""Phase 1 reconciliation: the historical plans A-D on the development
seeds, as archived by the dynamic-staffing benchmark
(../dynamic-staffing/results/dev, engine 0.2.0-dev.4, and reading-dev,
0.2.0-dev.5), against the same plans recorded under v0.2-eval-2
(results/p1-historical). Two parts:

1. Simulation identity: every archived daily sample (cumulative operating
   profit, cash, reports, backlog, days 1-180) against the new record's
   sample of the same day. Any difference is a simulation difference.
2. Measurement differences: the archived T90 and days 91-180 breach rates
   (as-of-window-end rule) beside the new evaluation's legacy rule and its
   breach-at-due cohorts, so that every difference in a reported figure is
   traced to a changed definition.

    python3 docs/calibration/strategy-development/reconcile.py

writes results/p1-historical/reconciliation.md.
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DYN = os.path.join(HERE, "..", "dynamic-staffing", "results")
OUT = os.path.join(HERE, "results", "p1-historical")
ARCHIVE = {  # plan -> (archived result file, its name there)
    "A-no-action": [("reading-dev", "A-no-action"), ("dev", "A-no-action")],
    "B-partial": [("dev", "B1-mr-evening")],
    "C-full-reorganization": [("reading-dev", "C-full-reorganization"), ("dev", "C-full-reorganization")],
    "D-full-reading": [("reading-dev", "D-full-reading")],
}
PRI = ["urgent", "soon", "routine"]


def main():
    traj = {}
    for row in csv.DictReader(open(os.path.join(OUT, "trajectory.csv"))):
        traj[(row["plan"], int(row["seed"]), int(row["day"]))] = row
    rep = json.load(open(os.path.join(OUT, "report.json")))
    plans = {p["plan"]: p for p in rep["plans"]}
    o = []
    w = o.append
    w("# Phase 1 reconciliation: archived A–D against v0.2-eval-2")
    w("")
    w("Generated by `reconcile.py`. The archived files are the dynamic-staffing benchmark's development-seed results; "
      "the new ones are `report.json` and `trajectory.csv` of this run. Nothing archived was modified.")
    w("")
    w("## 1. Simulation identity (daily samples, days 1–180)")
    w("")
    w("| Plan | Archived file (engine) | Seeds | Samples compared | Profit | Cash | Final reports | Backlog |")
    w("|---|---|---|---|---|---|---|---|")
    for plan, srcs in ARCHIVE.items():
        for d, name in srcs:
            a = json.load(open(os.path.join(DYN, d, name + ".json")))
            n = 0
            diff = {"profit": 0, "cash": 0, "reports": 0, "backlog": 0}
            for ps in a["perSeed"]:
                s = ps["seed"]
                dl = ps["daily"]
                for i in range(len(dl["profitCents"])):
                    t = traj[(plan, s, i + 1)]
                    n += 1
                    diff["profit"] += dl["profitCents"][i] != int(t["profitCents"])
                    diff["cash"] += dl["cashCents"][i] != int(t["cashCents"])
                    diff["reports"] += dl["reports"][i] != int(t["finalCum"])
                    diff["backlog"] += dl["backlog"][i] != int(t["backlog"])
            w("| %s | `%s/%s.json` (%s) | %d | %d | %s | %s | %s | %s |" % (
                plan, d, name, a["engine"], len(a["perSeed"]), n,
                *[("identical" if diff[x] == 0 else "**%d differ**" % diff[x]) for x in ("profit", "cash", "reports", "backlog")]))
    w("")
    w("Final reports are cumulative since the takeover in both.")
    w("")
    w("## 2. What changed in the measurement")
    w("")
    w("Breach rates, %, pooled over the 10 seeds (breaches ÷ acquired). *Archived* is the historical rule "
      "(as of the window's end: completed over target plus unfinished past target). *Legacy* is the same rule "
      "recomputed by `internal/eval` from the new record. *v0.2-eval-2* decides each study at its due time, "
      "observed through the closure.")
    w("")
    w("| Plan | Window | Archived U / S / R | Legacy (eval) U / S / R | v0.2-eval-2 U / S / R | Acquired U / S / R (archived → eval) |")
    w("|---|---|---|---|---|---|")
    for plan, srcs in ARCHIVE.items():
        d, name = srcs[0]
        a = json.load(open(os.path.join(DYN, d, name + ".json")))
        for win, aw in (("T90", "T90"), ("tail", None)):
            if aw is None:
                continue
            arch = {q: [0, 0] for q in PRI}
            for ps in a["perSeed"]:
                t = ps["windows"][aw]["tatByPriority"]
                for q in PRI:
                    arch[q][0] += t[q]["breaches"]
                    arch[q][1] += t[q]["acquired"]
            leg = {q: [0, 0] for q in PRI}
            new = {q: [0, 0] for q in PRI}
            for sr in plans[plan]["perSeed"]:
                c = sr["measures"]["windows"][win]["cohorts"]
                for q in PRI:
                    leg[q][0] += c[q]["legacyBreaches"]
                    leg[q][1] += c[q]["acquired"]
                    new[q][0] += c[q]["breaches"]
                    new[q][1] += c[q]["acquired"]
            f = lambda x: " / ".join("%.1f" % (100 * x[q][0] / x[q][1]) for q in PRI)
            w("| %s | %s | %s | %s | %s | %s |" % (plan, win, f(arch), f(leg), f(new),
                                                   " / ".join("%d → %d" % (arch[q][1], new[q][1]) for q in PRI)))
    w("")
    w("Days 91–180 (archived span) against the new tail (days 91–150) and T180:")
    w("")
    w("| Plan | Archived D91–180 U / S / R | v0.2-eval-2 tail (91–150) U / S / R | v0.2-eval-2 T180 U / S / R |")
    w("|---|---|---|---|")
    for plan, srcs in ARCHIVE.items():
        d, name = srcs[0]
        a = json.load(open(os.path.join(DYN, d, name + ".json")))
        arch = {q: [0, 0] for q in PRI}
        for ps in a["perSeed"]:
            t = ps["spans"]["D91-180"]["tatByPriority"]
            for q in PRI:
                arch[q][0] += t[q]["breaches"]
                arch[q][1] += t[q]["acquired"]
        res = {}
        for win in ("tail", "T180"):
            x = {q: [0, 0] for q in PRI}
            for sr in plans[plan]["perSeed"]:
                c = sr["measures"]["windows"][win]["cohorts"]
                for q in PRI:
                    x[q][0] += c[q]["breaches"]
                    x[q][1] += c[q]["acquired"]
            res[win] = x
        f = lambda x: " / ".join("%.1f" % (100 * x[q][0] / x[q][1]) for q in PRI)
        w("| %s | %s | %s | %s |" % (plan, f(arch), f(res["tail"]), f(res["T180"])))
    w("")
    w("Operating profit, $k, mean over seeds (archived window profit against the evaluation's captures):")
    w("")
    w("| Plan | Archived T30 / T90 / T180 | v0.2-eval-2 T30 / T90 / T180 |")
    w("|---|---|---|")
    for plan, srcs in ARCHIVE.items():
        d, name = srcs[0]
        a = json.load(open(os.path.join(DYN, d, name + ".json")))
        arch = [sum(ps["windows"][x]["profitCents"] for ps in a["perSeed"]) / len(a["perSeed"]) / 1e5 for x in ("T30", "T90", "T180")]
        op = plans[plan]["operatingProfitCents"]
        w("| %s | %s | %s |" % (plan, " / ".join("%.2f" % v for v in arch), " / ".join("%.2f" % (op[x]["mean"] / 1e5) for x in ("T30", "T90", "T180"))))
    w("")
    open(os.path.join(OUT, "reconciliation.md"), "w").write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
