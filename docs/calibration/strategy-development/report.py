#!/usr/bin/env python3
"""Tables for a Slice 5C.1 development run, from its committed outputs
(results/<set>/report.json, the frozen policy's evaluation, and
trajectory.csv). It reads nothing else and decides nothing: every status,
verdict and classification is the evaluation's own.

    python3 docs/calibration/strategy-development/report.py SET [SET...]

writes results/<set>/report.md.
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PRI = ["urgent", "soon", "routine"]
WINS = ["T30", "T90", "D31-90", "tail", "T180"]
K = 100000.0  # cents per $k


def k(c):
    return "%.1f" % (c / K)


def iv(x, scale=K, fmt="%.1f"):
    if not x or not x.get("defined"):
        return "—"
    m = fmt % (x["mean"] / scale)
    if x.get("n", 0) > 1 and x["hi"] != x["lo"]:
        return "%s [%s, %s]" % (m, fmt % (x["lo"] / scale), fmt % (x["hi"] / scale))
    return m


def pct(r):
    if not r or not r.get("defined"):
        return "—"
    return "%.1f" % (100 * r["value"])


def short(plan):
    return plan.split("-")[0]


def gates_failed(sr):
    """A seed's failing or insufficient per-seed gated gates, as codes."""
    out = []
    for g in sr["gates"]:
        if not g["perSeed"] or g["window"] not in ("gated", "T90", "tail"):
            continue
        if g["status"] != "pass":
            code = "%s %s %s %.1f%%" % (g["stratum"][0].upper(), g["window"], "fail" if g["status"] == "fail" else "insuff.",
                                       100 * g["value"])
            out.append(code)
    return out


def main(sid):
    d = os.path.join(HERE, "results", sid)
    rep = json.load(open(os.path.join(d, "report.json")))
    run = json.load(open(os.path.join(d, "run.json")))
    plans = {p["plan"]: p for p in rep["plans"]}
    base = rep["baseline"]
    comps = {c["candidate"]: c for c in rep["comparisons"] if c["against"] == base}
    pairs = [c for c in rep["comparisons"] if c["against"] != base]
    names = [p["plan"] for p in rep["plans"]]
    seeds = run["seeds"]
    o = []
    w = o.append
    w("# Development run `%s`" % sid)
    w("")
    w("Generated by `report.py` from `report.json` (policy `%s`, digest `%s`), engine `%s`, seeds %d–%d, "
      "common horizon day %.0f. Development evidence only: 10 seeds, exploratory (README)." %
      (rep["policyId"], rep["policyDigest"][:12], run["engine"], seeds[0], seeds[-1],
       (rep["horizonEndSec"] - plans[base]["perSeed"][0]["measures"]["windows"]["T90"]["fromSec"]) / 86400))
    if rep["integrity"]:
        w("")
        w("**Evaluation integrity failures:** " + "; ".join(rep["integrity"]))
    w("")
    w("## Verdicts")
    w("")
    w("| Plan | Valid | Service (joint: failing / insufficient seeds, limit) | Pooled + joint | Backlog stable | Solvent | Funding gap seeds | Case selection | Verdict | Classification |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for n in names:
        p = plans[n]
        j = p["serviceJoint"]
        c = comps.get(n)
        w("| %s | %s | %s / %s (≤ %d) | %s | %d / %d | %s | %s | %s | %s | %s |" % (
            n, "yes" if p["valid"] else "**no**", ",".join(str(s) for s in j["failingSeeds"]) or "none",
            ",".join(str(s) for s in j["insufficientSeeds"]) or "none", j["failLimit"], p["serviceStatus"],
            p["backlogStableSeeds"], len(p["seeds"]), p["solvencyStatus"],
            ",".join(str(s) for s in p["fundingGapSeeds"]) or "none",
            c["caseSelectionStatus"] if c else "—", c["verdict"] if c else "(baseline)", c["classification"] if c else "—"))
    w("")
    for n in names:
        c = comps.get(n)
        if c and c.get("reasons"):
            w("* **%s**: %s" % (n, "; ".join(c["reasons"])))
    w("")

    w("## Service: pooled breach rates (%), with the worst seed and the dispersion index")
    w("")
    w("Gated: T90 and the tail per priority (pooled), urgent over the gated period per seed. T180 is validation; T30 and D31–90 are informational.")
    w("")
    w("| Plan | Window | Urgent | Soon | Routine | Worst seed U / S / R | Seeds passing U / S / R | Dispersion U / S / R |")
    w("|---|---|---|---|---|---|---|---|")
    for n in names:
        gs = {(g["window"], g["stratum"]): g for g in plans[n]["serviceGates"]}
        for win in ["gated", "T90", "tail", "T180", "T30", "D31-90"]:
            row = [gs.get((win, q)) for q in PRI]
            if not any(row):
                continue
            def cell(g):
                return pct(g["pooled"]) if g else "—"
            def worst(g):
                return "%.1f (%d)" % (100 * g["worst"]["value"], g["worst"]["seed"]) if g and g["worst"]["defined"] else "—"
            def passing(g):
                return "%d/%d" % (g["passing"], g["seeds"]) if g else "—"
            def disp(g):
                return "%.2f" % g["dispersion"] if g and g["dispersion"] else "—"
            w("| %s | %s | %s | %s | %s | %s | %s | %s |" % (short(n), win, *[cell(g) for g in row], " / ".join(worst(g) for g in row),
                                                             " / ".join(passing(g) for g in row), " / ".join(disp(g) for g in row)))
    w("")

    w("## Per-seed service eligibility")
    w("")
    w("Each seed's failing (or insufficient) per-seed gates: U = urgent over the gated period, S/R = soon/routine in T90 or the tail. A seed fails if any fails.")
    w("")
    w("| Seed | " + " | ".join(short(n) for n in names) + " |")
    w("|---|" + "---|" * len(names))
    for i, s in enumerate(seeds):
        cells = []
        for n in names:
            sr = plans[n]["perSeed"][i]
            f = gates_failed(sr)
            cells.append("pass" if sr["service"] == "pass" else "; ".join(f))
        w("| %d | %s |" % (s, " | ".join(cells)))
    w("")

    w("## Backlog")
    w("")
    w("| Plan | Stable seeds | Unstable seeds: reasons | Persistent studies (max seed) | Worst past due, h | Legacy rule |")
    w("|---|---|---|---|---|---|")
    for n in names:
        p = plans[n]
        bad = []
        pers, worst = 0, 0.0
        for sr in p["perSeed"]:
            b = sr["measures"]["backlog"]
            pers = max(pers, b["persistentStudies"])
            worst = max(worst, b["worstPastDueHours"])
            if b["status"] != "stable":
                bad.append("%d: %s" % (sr["seed"], "; ".join(b.get("reasons") or [b["status"]])))
        w("| %s | %d / %d | %s | %d | %.0f | %s |" % (short(n), p["backlogStableSeeds"], len(p["seeds"]), "<br>".join(bad) or "—", pers, worst, p["legacyBacklogRule"]))
    w("")
    w("Backlog block means (studies, mean over seeds), reference block first:")
    w("")
    w("| Plan | " + " | ".join("days %d–%d" % (b["firstDay"], b["lastDay"]) for b in [plans[base]["perSeed"][0]["measures"]["backlog"]["reference"]] + plans[base]["perSeed"][0]["measures"]["backlog"]["later"]) + " | overdue (ref → last) | stale (ref → last) |")
    w("|---|" + "---|" * (len(plans[base]["perSeed"][0]["measures"]["backlog"]["later"]) + 3))
    for n in names:
        ps = plans[n]["perSeed"]
        blocks = [[sr["measures"]["backlog"]["reference"]] + sr["measures"]["backlog"]["later"] for sr in ps]
        means = [sum(b[i]["meanBacklog"] for b in blocks) / len(blocks) for i in range(len(blocks[0]))]
        od = [sum(b[i]["overdueMean"] for b in blocks) / len(blocks) for i in (0, -1)]
        st = [sum(b[i]["staleMean"] for b in blocks) / len(blocks) for i in (0, -1)]
        w("| %s | %s | %.1f → %.1f | %.1f → %.1f |" % (short(n), " | ".join("%.1f" % m for m in means), od[0], od[1], st[0], st[1]))
    w("")

    w("## Access and case selection (against %s)" % base)
    w("")
    w("| Plan | Status | Failing strata | Insufficient (blocking) | T90 served % | T90 lost-referral % | Carried in (T90) served / open at end | Inherited due / served / open |")
    w("|---|---|---|---|---|---|---|---|")
    for n in names:
        ps = plans[n]["perSeed"]
        def tot(f):
            return sum(f(sr["measures"]) for sr in ps)
        due = tot(lambda m: m["windows"]["T90"]["access"]["due"])
        srv = tot(lambda m: m["windows"]["T90"]["access"]["served"])
        refs = tot(lambda m: m["windows"]["T90"]["access"]["referrals"])
        lost = tot(lambda m: m["windows"]["T90"]["access"]["lostReferrals"])
        ci = tot(lambda m: m["windows"]["tail"]["access"]["carriedIn"])
        cis = tot(lambda m: m["windows"]["tail"]["access"]["carriedInServed"])
        cio = tot(lambda m: m["windows"]["tail"]["access"]["carriedInOpenAtEnd"])
        ih = [tot(lambda m: m["inherited"][x]) for x in ("due", "served", "openAtEnd")]
        c = comps.get(n)
        fail = ins = "—"
        if c:
            fail = ", ".join("%s %s %s" % (g["gate"], g["window"], g.get("stratum", "")) for g in c["caseSelection"] if g["status"] == "fail") or "none"
            ins = ", ".join("%s %s" % (g["window"], g.get("stratum", "")) for g in c["caseSelection"] if g["status"] == "insufficient" and g.get("blocking")) or "none"
        w("| %s | %s | %s | %s | %.1f | %.1f | %d: %d / %d | %d / %d / %d |" % (short(n), c["caseSelectionStatus"] if c else "(baseline)", fail, ins,
                                                                       100 * srv / max(due, 1), 100 * lost / max(refs, 1), ci, cis, cio, *ih))
    w("")
    w("Carried in = orders due before the tail and still open at T90 (the tail's carried-in orders), summed over seeds.")
    w("")

    w("## Reports, local and remote (sum over seeds)")
    w("")
    w("| Plan | Window | Local | Remote | Remote claims | Remote TAT p50 / p90 min | Retainer $k | Read fees $k | Cost per remote report $ |")
    w("|---|---|---|---|---|---|---|---|---|")
    for n in names:
        for win in ["T90", "tail", "T180"]:
            rs = [sr["measures"]["windows"][win]["remote"] for sr in plans[n]["perSeed"]]
            loc, rem, cl = (sum(r[x] for r in rs) for x in ("localReports", "remoteReports", "remoteClaims"))
            ret, fee = sum(r["retainerCents"] for r in rs), sum(r["readFeeCents"] for r in rs)
            tat = [r["remoteTatMin"] for r in rs if r["remoteTatMin"]["defined"]]
            w("| %s | %s | %d | %d | %d | %s | %s | %s | %s |" % (short(n), win, loc, rem, cl,
                                                                "%d / %d" % (sorted(t["p50"] for t in tat)[len(tat) // 2], max(t["p90"] for t in tat)) if tat else "—",
                                                                k(ret), k(fee), "%.0f" % ((ret + fee) / 100 / rem) if rem else "—"))
    w("")

    w("## Finance")
    w("")
    w("Own operating profit, $k, mean [95% t interval] over seeds:")
    w("")
    w("| Plan | " + " | ".join(WINS) + " | Margin T90 % | Margin T180 % |")
    w("|---|" + "---|" * (len(WINS) + 2))
    for n in names:
        p = plans[n]
        def margin(win):
            m = [sr["measures"]["windows"][win]["money"] for sr in p["perSeed"]]
            return "%.1f" % (100 * sum(x["operatingProfitCents"] for x in m) / sum(x["netRevenueCents"] for x in m))
        w("| %s | %s | %s | %s |" % (short(n), " | ".join(iv(p["operatingProfitCents"].get(x)) for x in WINS), margin("T90"), margin("T180")))
    w("")
    w("Incremental against %s (paired), $k:" % base)
    w("")
    w("| Plan | " + " | ".join("Δ profit " + x for x in WINS) + " | Worst Δ T90 (seed) | Δ cash T90 / T180 | Δ min cash | Δ revenue T90 | Δ reports T90 / T180 |")
    w("|---|" + "---|" * (len(WINS) + 5))
    for n in names:
        c = comps.get(n)
        if not c:
            continue
        wp = c["worstIncrementalProfitSeed"].get("T90", {})
        w("| %s | %s | %s | %s / %s | %s | %s | %s / %s |" % (
            short(n), " | ".join(iv(c["incrementalProfitCents"].get(x)) for x in WINS),
            "%s (%d)" % (k(wp["value"]), wp["seed"]) if wp.get("defined") else "—",
            iv(c["incrementalCashCents"].get("T90")), iv(c["incrementalCashCents"].get("T180")), iv(c["minCashDeltaCents"]),
            iv(c["incrementalNetRevenueCents"].get("T90")), iv(c["incrementalReports"].get("T90"), 1, "%.0f"), iv(c["incrementalReports"].get("T180"), 1, "%.0f")))
    w("")
    w("Cash, obligations and payback:")
    w("")
    w("| Plan | Lowest cash $k (worst seed) | Mean of seed minima $k | Largest funding gap $k (seed) | Obligations at T90 / end $k (mean) | Accrual payback 90 / 180 (repaid, median day) | Cash payback 90 / 180 |")
    w("|---|---|---|---|---|---|---|")
    for n in names:
        p = plans[n]
        ms = [sr["measures"] for sr in p["perSeed"]]
        gap = max(ms, key=lambda m: m["fundingGapCents"])
        ob90 = sum(m["windows"]["T90"]["money"]["obligationsCents"] for m in ms) / len(ms)
        obe = sum(m["windows"]["T180"]["money"]["obligationsCents"] for m in ms) / len(ms)
        c = comps.get(n)
        def pb(lst):
            out = []
            for x in lst or []:
                out.append("%d/%d, %s" % (x["repaid"], x["seeds"], ("day %d" % x["median"]) if x["medianDefined"] else "not reached"))
            return " ; ".join(out) or "—"
        w("| %s | %s (%d) | %s | %s | %s / %s | %s | %s |" % (short(n), k(p["worstMinCashCents"]), p["worstMinCashSeed"],
                                                          k(sum(m["minCashCents"] for m in ms) / len(ms)),
                                                          ("%s (%d)" % (k(gap["fundingGapCents"]), gap["seed"])) if gap["fundingGapCents"] > 0 else "none",
                                                          k(ob90), k(obe), pb(c["accrualPayback"]) if c else "—", pb(c["cashPayback"]) if c else "—"))
    w("")
    if pairs:
        w("## Candidate-to-candidate comparisons (informational, no verdict)")
        w("")
        w("| Candidate − against | Δ profit T90 / T180 $k | Δ revenue T90 / T180 $k | Δ reports T90 / T180 | Remote cost T90 / T180 $k | Δ breach T90 U / S / R pts | Δ breach tail U / S / R pts | Δ unbilled T90 $k |")
        w("|---|---|---|---|---|---|---|---|")
        for c in pairs:
            def bd(win):
                return " / ".join(iv(c["breachRateDelta"].get(win, {}).get(q), 0.01) for q in PRI)
            w("| %s − %s | %s / %s | %s / %s | %s / %s | %s / %s | %s | %s | %s |" % (
                short(c["candidate"]), short(c["against"]), iv(c["incrementalProfitCents"].get("T90")), iv(c["incrementalProfitCents"].get("T180")),
                iv(c["incrementalNetRevenueCents"].get("T90")), iv(c["incrementalNetRevenueCents"].get("T180")),
                iv(c["incrementalReports"].get("T90"), 1, "%.0f"), iv(c["incrementalReports"].get("T180"), 1, "%.0f"),
                iv(c["remoteCostCents"].get("T90")), iv(c["remoteCostCents"].get("T180")), bd("T90"), bd("tail"),
                iv(c["unbilledCompletedDeltaCents"].get("T90"))))
        w("")
    w("Breach deltas against %s, points (paired):" % base)
    w("")
    w("| Plan | T90 U / S / R | tail U / S / R | gated U |")
    w("|---|---|---|---|")
    for n in names:
        c = comps.get(n)
        if not c:
            continue
        def bd(win, qs=PRI):
            return " / ".join(iv(c["breachRateDelta"].get(win, {}).get(q), 0.01) for q in qs)
        w("| %s | %s | %s | %s |" % (short(n), bd("T90"), bd("tail"), bd("gated", ["urgent"])))
    w("")
    open(os.path.join(d, "report.md"), "w").write("\n".join(o))


if __name__ == "__main__":
    for s in sys.argv[1:]:
        main(s)
