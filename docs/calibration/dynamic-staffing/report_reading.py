#!/usr/bin/env python3
"""Plan D (full staffing + reading allocation) against plan C and no
action: results/reading-eval/*.json -> results/reading-eval/reading.md.
Also checks that A, B and C under this build reproduce the original
evaluation (results/eval) exactly.

    python3 docs/calibration/dynamic-staffing/report_reading.py [reading-eval|reading-dev] [eval]

Paired by seed. Spans: T30 = days 1-30; D31-90 and D91-180 are
differences of cumulative figures, or studies and orders of the span.
The decision rule is README.md's (fixed before any run of D).
"""
import json
import os
import sys

import report as R

HERE = os.path.dirname(os.path.abspath(__file__))
A, B, C, D = "A-no-action", "B-partial", "C-full-reorganization", "D-full-reading"
GATES = {"urgent": 12.0, "soon": 32.0, "routine": 6.0}  # owner's provisional T90 gates (V0.2_DESIGN §13.3)
SPANS = [("T30", 0, 30), ("D31-90", 30, 90), ("D91-180", 90, 180), ("T90", 0, 90), ("T180", 0, 180)]

# Fields a newer harness adds: absent from the original results.
NEW_FIELDS = {"backlogMeanAgeMin", "backlogP90AgeMin", "backlogRevenueCents", "readingSalaryCents"}


def strip(x):
    if isinstance(x, dict):
        return {k: strip(v) for k, v in x.items() if k not in NEW_FIELDS}
    if isinstance(x, list):
        return [strip(v) for v in x]
    return x


def same_outcomes(new, old):
    """Per-seed results equal except the engine name and the new fields."""
    a, b = strip(new), strip(old)
    for r in (a, b):
        r.pop("engine", None)
        r.pop("set", None)
    return a == b


def span(s, a, b, f):
    return f(s, b) - (f(s, a) if a else 0)


def reading(s, d):
    return R.k(s["labor"][f"T{d}"].get("readingSalaryCents", 0))


def main():
    set_ = sys.argv[1] if len(sys.argv) > 1 else "reading-eval"
    orig = sys.argv[2] if len(sys.argv) > 2 else ("eval" if set_ == "reading-eval" else "dev")
    rs = R.load(set_)
    seeds = rs[A]["seeds"]
    by = {p: {s["seed"]: s for s in rs[p]["perSeed"]} for p in rs}
    for p in rs:
        if rs[p]["seeds"] != seeds or rs[p]["scenarioFingerprint"] != rs[A]["scenarioFingerprint"]:
            sys.exit(f"{p}: seeds or scenario differ")
    L = []
    w = L.append
    w(f"# Plan D (full staffing + reading allocation) — `{set_}` set\n")
    w("Generated by `report_reading.py` from `results/%s/*.json`; do not edit by hand. Money in $k; "
      "± is a 95%% paired t half-width across seeds; ranges are min to max. The full four-plan "
      "tables are in `report.md` (same directory).\n" % set_)
    w(f"* Engine `{rs[A]['engine']}`; seeds {seeds[0]}–{seeds[-1]} ({len(seeds)}); {rs[A]['days']} days")
    for p in sorted(rs):
        w(f"* `{p}`: plan SHA-256 `{rs[p]['planSHA256'][:16]}…`")
    w("")

    # Neutrality against the original results.
    old = R.load(orig)
    w(f"## Reproduction of the original results (`results/{orig}`)\n")
    w("A plan without an allocation action must reproduce its original per-seed results exactly "
      "(every daily trajectory, window, span, labor figure and check), apart from the engine name and "
      "the fields this harness adds.\n")
    w("| plan | original engine | identical outcomes |")
    w("|---|---|---|")
    for p in sorted(rs):
        if p in old:
            w(f"| {p} | `{old[p]['engine']}` | {same_outcomes(rs[p], old[p])} |")
    w("")

    if D not in rs or C not in rs:
        open(os.path.join(HERE, "results", set_, "reading.md"), "w").write("\n".join(L) + "\n")
        return

    # Acceptance.
    w("## Plan D acceptance and lifecycle\n")
    dd = list(by[D].values())
    disp = [s["extra"]["T180"]["displacement"] for s in dd]
    w(f"* Actions accepted on every seed: {all(s['checks']['allAccepted'] for s in dd)} "
      f"({len(dd[0]['actions'])} actions: {', '.join(a['type'] + ' ' + a['target'] for a in dd[0]['actions'])})")
    w(f"* Lifecycle and allocations as planned on every seed: {all(s['checks']['lifecycleMatches'] for s in dd)}")
    w(f"* Displaced appointments (rebooked / lost): {sum(d.get('events', 0) for d in disp)} "
      f"({sum(d.get('rebooked', 0) for d in disp)} / {sum(d.get('noFeasibleSlot', 0) + d.get('declined', 0) for d in disp)}); "
      f"C: {sum(s['extra']['T180']['displacement'].get('events', 0) for s in by[C].values())}")
    w(f"* Cash bridge reconciled: {all(s['checks']['reconciled'] for s in dd)}; labor postings reconcile: "
      f"{all(s['checks']['laborReconciles'] for s in dd)}; inconsistent bookings: {sum(s['checks']['inconsistentBookings'] for s in dd)}")
    w("")

    pc = lambda f: [f(by[D][sd]) - f(by[C][sd]) for sd in seeds]
    pa = lambda p, f: [f(by[p][sd]) - f(by[A][sd]) for sd in seeds]

    # Reading expense, reports, revenue.
    w("## Reading expense, reports and revenue (D − C, paired)\n")
    w("Reading expense is the radiologists' salary with benefits (their site allocation). Backlog "
      "revenue is the net revenue the unfinished studies will recognize when reported: imaged, not "
      "yet billed.\n")
    w("| span | Δ reading expense | Δ final reports | Δ net revenue | Δ operating expense | Δ operating profit | seeds Δ profit > 0 |")
    w("|---|---|---|---|---|---|---|")
    for name, a, b in SPANS:
        ops = lambda s: sum(R.span_ops(s, a, b)["reports"].values())
        f = lambda key: (lambda s: R.fin(s, a, b)[key])
        dp = pc(f("profit"))
        w(f"| {name} | {R.cis(pc(lambda s: span(s, a, b, reading)), 2)} | {R.cis(pc(ops))} | {R.cis(pc(f('netRevenue')))} | "
          f"{R.cis(pc(f('opex')))} | {R.cis(dp)} | {sum(1 for x in dp if x > 0)}/{len(seeds)} |")
    w("")
    w("| endpoint | backlog revenue A / C / D | Δ D − C (recovered) |")
    w("|---|---|---|")
    for d in (30, 90, 180):
        br = lambda s: R.k(s["extra"][f"T{d}"]["backlogRevenueCents"])
        w(f"| T{d} | {R.fmt(R.mean([br(by[A][sd]) for sd in seeds]))} / {R.fmt(R.mean([br(by[C][sd]) for sd in seeds]))} / "
          f"{R.fmt(R.mean([br(by[D][sd]) for sd in seeds]))} | {R.cis(pc(br))} |")
    w("")

    # Service.
    w("## Reporting service\n")
    w("Breach rate: breaches ÷ studies acquired in the span, as of its end (means across seeds). Gates: "
      "the owner's provisional T90 gates. Seeds passing: all three gates met on that seed.\n")
    w("| plan | span | breach urgent / soon / routine % | gates met (mean) | seeds passing | urgent p90 min | backlog at end | oldest / mean / p90 age min |")
    w("|---|---|---|---|---|---|---|---|")
    rates = {}
    for p in (A, C, D):
        for name, a, b in SPANS:
            o = [R.span_ops(by[p][sd], a, b) for sd in seeds]
            br = {q: [R.breach_rate(x, q) for x in o] for q in R.PRIS}
            rates[(p, name)] = br
            met = all(R.mean(br[q]) <= GATES[q] for q in R.PRIS)
            npass = sum(1 for i in range(len(seeds)) if all(br[q][i] <= GATES[q] for q in R.PRIS))
            ex = [by[p][sd]["extra"][f"T{b}"] for sd in seeds]
            age = " / ".join(R.fmt(R.mean([x.get(f, 0) for x in ex]), 0) for f in ("backlogOldestMin", "backlogMeanAgeMin", "backlogP90AgeMin"))
            w(f"| {p} | {name} | {' / '.join(R.fmt(R.mean(br[q])) for q in R.PRIS)} | {met} | {npass}/{len(seeds)} | "
              f"{R.fmt(R.mean([x['tat'].get('urgent', {}).get('p90Min', 0) for x in o]), 0)} | {R.fmt(R.mean([x['backlog'] for x in ex]), 0)} | {age} |")
    w("")
    w("Paired breach-rate differences (points):\n")
    w("| span | D − C urgent | D − C soon | D − C routine | D − A urgent | D − A soon | D − A routine |")
    w("|---|---|---|---|---|---|---|")
    for name, _, _ in SPANS:
        cells = []
        for ref in (C, A):
            for q in R.PRIS:
                cells.append(R.cis([x - y for x, y in zip(rates[(D, name)][q], rates[(ref, name)][q])]))
        w(f"| {name} | " + " | ".join(cells) + " |")
    w("")

    # Access.
    w("## Imaging access and losses (D − C, paired)\n")
    w("| span | Δ exams | Δ lost referrals | Δ walk-ins left | Δ displaced |")
    w("|---|---|---|---|---|")
    for name, a, b in SPANS[:3]:
        o = lambda key: (lambda s: (lambda x: sum(x[key].values()) if isinstance(x[key], dict) else x[key])(R.span_ops(s, a, b)))
        w(f"| {name} | {R.cis(pc(o('exams')))} | {R.cis(pc(o('lost')))} | {R.cis(pc(o('walkInsLeft')))} | {R.cis(pc(o('displaced')))} |")
    w("")

    # Finance and cash.
    w("## Profit, cash and obligations\n")
    w("| plan | Δ profit vs no action T30 / T90 / T180 | Δ vs C T30 / T90 / T180 | margin D91–180 % | lowest cash (mean, min) | liabilities T30 / T90 / T180 | radiologist salary per 30 d (D91–180) |")
    w("|---|---|---|---|---|---|---|")
    for p in (A, B, C, D):
        if p not in rs:
            continue
        inc = [R.incremental(by[p][sd], by[A][sd]) for sd in seeds]
        incc = [R.incremental(by[p][sd], by[C][sd]) for sd in seeds]
        mins = [R.k(min(by[p][sd]["daily"]["cashCents"])) for sd in seeds]
        liab = lambda d: R.fmt(R.mean([R.k(by[p][sd]["extra"][f"T{d}"]["liabilitiesCents"]) for sd in seeds]))
        rad30 = R.mean([(reading(by[p][sd], 180) - reading(by[p][sd], 90)) / 90 * 30 for sd in seeds])
        vs_a = "—" if p == A else " / ".join(R.cis([x[d - 1] for x in inc]) for d in (30, 90, 180))
        vs_c = "—" if p == C else " / ".join(R.cis([x[d - 1] for x in incc]) for d in (30, 90, 180))
        w(f"| {p} | {vs_a} | {vs_c} | {R.fmt(R.mean([R.fin(by[p][sd], 90, 180)['margin'] for sd in seeds]))} | "
          f"{R.fmt(R.mean(mins))}, {R.fmt(min(mins))} | {liab(30)} / {liab(90)} / {liab(180)} | {R.fmt(rad30)} |")
    w("")
    w("Liabilities: payables + accrued payroll + severance payable. An allocation is a recurring "
      "obligation, not a lump sum: it binds from its effective date until a later change, which needs "
      "14 days' notice.\n")

    # Payback.
    w("## Payback against no action\n")
    w("Break-even: the first day from which the cumulative increment over the paired no-action run "
      "stays at or above zero through day 180. Steady state: the increment's change over days 91–180, "
      "per 30 days.\n")
    w("| plan | steady state Δ / 30 d | accrual break-even day: median (range) | by T90 / T180 | cash break-even: median | cash paid back by T180 |")
    w("|---|---|---|---|---|---|")
    med = lambda xs: xs[len(xs) // 2] if xs else None
    for p in (B, C, D):
        if p not in rs:
            continue
        incs = [R.incremental(by[p][sd], by[A][sd]) for sd in seeds]
        cinc = [R.incremental(by[p][sd], by[A][sd], "cashCents") for sd in seeds]
        be = sorted(b for b in (R.sustained_breakeven(x) for x in incs) if b is not None)
        cb = sorted(b for b in (R.sustained_breakeven(x) for x in cinc) if b is not None)
        w(f"| {p} | {R.cis([(x[179] - x[89]) / 90 * 30 for x in incs])} | {med(be) if be else 'none'}"
          f"{f' ({be[0]}–{be[-1]})' if be else ''} | {sum(1 for b in be if b <= 90)} / {len(be)} of {len(seeds)} | "
          f"{med(cb) if cb else 'none'} | {len(cb)} of {len(seeds)} |")
    incs = [R.incremental(by[D][sd], by[C][sd]) for sd in seeds]
    be = sorted(b for b in (R.sustained_breakeven(x) for x in incs) if b is not None)
    w(f"| D − C (the allocation alone) | {R.cis([(x[179] - x[89]) / 90 * 30 for x in incs])} | "
      f"{med(be) if be else 'none'}{f' ({be[0]}–{be[-1]})' if be else ''} | {sum(1 for b in be if b <= 90)} / {len(be)} of {len(seeds)} | — | — |")
    w("")

    # Decision rule.
    w("## Decision rule (README, fixed before any run)\n")
    ok_gates = {name: all(R.mean(rates[(D, name)][q]) <= GATES[q] for q in R.PRIS) for name in ("T90", "D91-180")}
    b90 = R.mean([by[D][sd]["extra"]["T90"]["backlog"] for sd in seeds])
    b180 = R.mean([by[D][sd]["extra"]["T180"]["backlog"] for sd in seeds])
    stable = b180 <= 1.1 * b90
    inc180 = [R.incremental(by[D][sd], by[A][sd])[179] for sd in seeds]
    m180, h180 = R.ci(inc180)
    du = [x - y for x, y in zip(rates[(D, "D91-180")]["urgent"], rates[(C, "D91-180")]["urgent"])]
    mu, hu = R.ci(du)
    du90 = [x - y for x, y in zip(rates[(D, "T90")]["urgent"], rates[(C, "T90")]["urgent"])]
    mu90, hu90 = R.ci(du90)
    acceptable = ok_gates["T90"] and ok_gates["D91-180"] and stable
    benefit = m180 - h180 > 0
    improves = (mu + hu < 0) or (mu90 + hu90 < 0)
    if acceptable and benefit:
        verdict = "GO"
    elif improves and m180 > 0:
        verdict = "CONDITIONAL GO"
    else:
        verdict = "NO GO"
    w(f"* Gates met by D (means): T90 {ok_gates['T90']}, days 91–180 {ok_gates['D91-180']}")
    w(f"* Backlog not growing (T180 ≤ 1.1 × T90): {stable} ({R.fmt(b90, 0)} → {R.fmt(b180, 0)})")
    w(f"* T180 profit over no action: {R.fmt(m180)} ± {R.fmt(h180)} $k (positive with 95% interval above zero: {benefit})")
    w(f"* Urgent breach D − C: T90 {R.fmt(mu90)} ± {R.fmt(hu90)}, days 91–180 {R.fmt(mu)} ± {R.fmt(hu)} points (significant reduction: {improves})")
    w(f"\n**Rule outcome: {verdict}.**\n")
    w("## Supplementary: backlog trend (not part of the rule)\n")
    w("The rule's backlog test compares single samples at day 90 (a Monday, 06:00) and day 180 (a "
      "Sunday, 06:00). Mean daily backlog (unread + reading at each day's 06:00 sample) by 30-day block:\n")
    w("| plan | days 61–90 | 91–120 | 121–150 | 151–180 |")
    w("|---|---|---|---|---|")
    for p in (A, C, D):
        blk = lambda a, b: R.mean([sum(by[p][sd]["daily"]["backlog"][a:b]) / (b - a) for sd in seeds])
        w(f"| {p} | " + " | ".join(R.fmt(blk(a, a + 30)) for a in (60, 90, 120, 150)) + " |")
    w("")
    open(os.path.join(HERE, "results", set_, "reading.md"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
